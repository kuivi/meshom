"""Benchmark records: timed stages with peak RSS and machine info, JSON lines, a Markdown table."""
import datetime
import json
import platform
import resource
import subprocess
import sys
import time
from contextlib import contextmanager
from functools import lru_cache
from pathlib import Path

import numpy as np

_TABLE = ("date", "host", "commit", "mesh", "stage", "n_nodes", "wall_s", "peak_rss_mb")


def _cpu() -> str:
    if sys.platform == "darwin":
        r = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True)
        if r.returncode == 0:
            return r.stdout.strip()
    if Path("/proc/cpuinfo").exists():
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    return platform.processor()


@lru_cache(maxsize=1)
def machine_info() -> dict:
    r = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                       cwd=Path(__file__).resolve().parent)
    return {"host": platform.node(), "platform": platform.platform(), "cpu": _cpu(),
            "python": platform.python_version(), "numpy": np.__version__,
            "commit": r.stdout.strip() if r.returncode == 0 else "unknown"}


def _peak_rss_mb() -> float:
    """This process's own high-water mark of the resident set (MB). Linux: VmHWM of /proc/self/status, which starts
    afresh at exec; ru_maxrss would not do there, a child started by subprocess inherits the parent's ru_maxrss
    through fork + exec (a runner holding 1.5 GB made every child report >= 1.5 GB). macOS: ru_maxrss (bytes), per
    process."""
    if sys.platform.startswith("linux"):
        for line in Path("/proc/self/status").read_text().splitlines():
            if line.startswith("VmHWM:"):
                return int(line.split()[1]) / 2**10               # kB
    r = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return r / 2**20 if sys.platform == "darwin" else r / 2**10


@contextmanager
def stage(name: str, records: list[dict], **meta):
    """Time the block; append {date, stage, wall_s, peak_rss_mb, machine_info, meta} to records on exit.

    Yields the meta dict, so the block can add values known only inside it (e.g. n_nodes after a read).
    """
    t0 = time.perf_counter()
    yield meta
    wall = time.perf_counter() - t0
    records.append({"date": datetime.datetime.now().isoformat(timespec="seconds"), "stage": name,
                    "wall_s": wall, "peak_rss_mb": _peak_rss_mb(), **machine_info(), **meta})


def append_jsonl(records: list[dict], path: Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")


def _fmt(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        return f"{v:.3g}" if abs(v) < 100 else f"{v:.0f}"
    return str(v)


def render_markdown(path: Path) -> str:
    path = Path(path)
    text = path.read_text() if path.exists() else ""
    recs = [json.loads(line) for line in text.splitlines() if line.strip()]
    lines = ["# Benchmarks", "", f"Generated by `meshom bench-table` from `{path.as_posix()}`. Peak RSS is the "
             "process's own high-water mark at the end of the stage.", "",
             "| " + " | ".join(_TABLE) + " |", "|" + "---|" * len(_TABLE)]
    for r in recs:
        lines.append("| " + " | ".join(_fmt(r.get(k)) for k in _TABLE) + " |")
    return "\n".join(lines) + "\n"
